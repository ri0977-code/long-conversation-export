    function exportResult(
        title,
        screens,
        info,
        repaired
    ) {

        // 从指定位置开始：最后一道保险 —— 锚点之前的一律裁掉。
        // 扫描过程中不管位置怎么漂，只要锚点那条抓到了就切得准。
        info.trimmed = 0;

        if (
            info.mode === 'fromHere'
        ) {

            if (info.anchor) {

                info.trimmed =
                    trimAboveStart(
                        info.anchor
                    );

            } else {

                // 没有锚点就退化成按 Y 裁剪（半屏冗余）
                const floor =
                    info.startY -
                    Math.round(
                        window.innerHeight *
                        0.5
                    );

                const before =
                    messages.length;

                const kept =
                    messages.filter(
                        m =>
                            typeof m.firstY !==
                            'number' ||
                            m.firstY >= floor
                    );

                if (
                    kept.length !==
                    before
                ) {

                    messages.length = 0;

                    messages.push(
                        ...kept
                    );
                }

                info.trimmed =
                    before - kept.length;
            }
        }

        finalizeMessages();

        const md =
            makeMarkdown(
                title,
                screens,
                info
            );

        const txt =
            makeTxt(title);

        const report =
            makeReport(
                title,
                screens,
                info
            );

        const stamp =
            timestamp();

        // =================================================
        // 文件名规则
        //
        // 主体 = 左侧对话列表里的当前对话名称
        // （面板输入框里显示的就是它，可以直接改）
        // 后缀 = 导出时间戳 + 局部/中止标记
        // =================================================

        let tag = '';

        if (
            info.mode === 'fromHere'
        ) {
            tag += '_从指定位置';
        }

        if (info.aborted) {
            tag += '_中止';
        }

        // 文件名后缀：AI 来源 id，让下载下来的对话单独拿出来也能一眼看出是哪个 AI。
        // 主人 2026-09-10 提出"先看的是内容再看谁说的"——AI 标识放末尾，
        // 文件名整体阅读顺序是"对话标题_时间戳_扫描模式_AI源"，人类先关注内容再看来源。
        const aiTag = getSelectedAI();
        const base =
            `${safeFileName(title)}_${stamp}${tag}_${aiTag}`;

        downloadText(
            md,
            `${base}.md`,
            'text/markdown'
        );

        setTimeout(
            () => {
                downloadText(
                    txt,
                    `${base}.txt`,
                    'text/plain'
                );
            },
            400
        );

        setTimeout(
            () => {
                downloadText(
                    report,
                    `${base}_扫描报告.txt`,
                    'text/plain'
                );
            },
            800
        );

        const anomalyCount =
            messages.reduce(
                (n, m, i) => {

                    if (i === 0) {
                        return n;
                    }

                    return n +
                        (
                            messages[i - 1].role ===
                            m.role
                                ? 1
                                : 0
                        );
                },
                0
            );

        setStatus(
            (
                info.aborted
                    ? '已停止 · 导出已抓到的部分\n'
                    : '扫描完成\n'
            ) +
            `${messages.length} 条消息 · ` +
            `${screens} 屏\n` +
            `起点：${
                info.mode === 'fromHere'
                    ? `指定位置 Y=${info.startY}`
                    : '真正顶部'
            }` +
            (
                info.aborted
                    ? ''
                    : `  到底：${
                        info.bottomOK ? '✓' : '✗'
                    }`
            ),
            messages.length
        );

        ui.report.textContent =
            `已导出：\n` +
            `${base}.md\n` +
            `${base}.txt\n` +
            `${base}_扫描报告.txt\n` +
            (
                info.mode === 'fromHere'
                    ? `从指定位置 Y=${info.startY} 开始\n` +
                    (
                        info.trimmed
                            ? `裁掉起点以上 ${info.trimmed} 条\n`
                            : '（起点以上无多余内容）\n'
                    ) +
                    (
                        info.anchor
                            ? `锚点：「${info.anchor.key
                                .slice(0, 24)
                                .replace(/\n/g, ' ')}…」\n`
                            : ''
                    )
                    : ''
            ) +
            `补扫：${repaired.gaps} 处空洞，` +
            `补回 ${repaired.fixed} 条\n` +
            `结构异常候选：${anomalyCount} 处`;

        setTimeout(
            () => {
                ui.panel.style.display =
                    'none';
            },
            6000
        );
    }

