    // 收集消息
    // =========================================================

    function collectMessages(
        scroller,
        screenNo
    ) {

        const nodes =
            getMessageElements(
                scroller
            );

        const found = [];

        for (const el of nodes) {

            if (
                !isVisibleMessage(
                    el,
                    scroller,
                    visibleOpts()
                )
            ) {
                continue;
            }

            let role =
                detectRole(el);

            if (
                role !== 'user' &&
                role !== 'assistant' &&
                role !== 'system'
            ) {

                // 通用站点判定不出角色时按「一问一答」交替兜底
                role =
                    nodes.indexOf(el) % 2 === 0
                        ? 'user'
                        : 'assistant';
            }

            const text =
                normalizeText(
                    el.innerText ||
                    el.textContent ||
                    ''
                );

            if (!text) continue;

            if (isUiNoise(text)) {
                continue;
            }

            observationCount++;

            const stableId =
                getStableId(el);

            const mapped =
                elementMessageMap.get(el);

            if (mapped) {

                // 虚拟列表会**复用 DOM 元素**（grok / Claude 都是这种
                // 机制）：滚过去之后元素还是同一个元素，内容却已经
                // 换成另一条消息了。此时如果直接复用 mapped，
                // 整条对话会被压成「一屏能显示的条数」（grok 实测
                // 28 条只剩 6 条）。
                // 判据：内容变了 **并且** 绝对位置也差很远
                // —— 说明元素被复用成了另一条消息，必须新建。
                // （内容变但位置没变 = 同一条消息的流式输出，仍复用）

                const rM =
                    el.getBoundingClientRect();

                const absYM =
                    Math.round(
                        rM.top +
                        scroller.scrollTop
                    );

                const changed =
                    mapped.textHash !==
                    hashText(text);

                const farAway =
                    Math.abs(
                        mapped.lastY - absYM
                    ) >
                    Math.max(
                        220,
                        scroller.clientHeight *
                        0.85
                    );

                if (
                    !(changed && farAway)
                ) {

                    mapped.text = text;

                    mapped.textHash =
                        hashText(text);

                    mapped.lastScreen =
                        screenNo;

                    mapped.observations++;

                    duplicateObservationCount++;

                    found.push(mapped);

                    continue;
                }

                // 否则：元素被复用成了另一条消息，继续走新建流程
            }

            let existing = null;

            if (stableId) {

                existing =
                    messages.find(
                        m =>
                            m.stableId ===
                            stableId
                    );

                // id 相同但内容不同时，要区分两种情况：
                //   a) 同一条消息在流式输出/后续补采时文本变长
                //      —— 位置几乎不变，应视为同一条（沿用旧行为）
                //   b) id 本身不唯一，比如 grok 所有用户消息的
                //      data-testid 都是 "user-message"，
                //      直接复用会把 28 条压成 2 条 —— 位置会差很远
                // 用「绝对位置」把两者分开。
                if (existing) {

                    const h =
                        hashText(text);

                    if (
                        existing.textHash !==
                        h
                    ) {

                        const r0 =
                            el.getBoundingClientRect();

                        const absY0 =
                            Math.round(
                                r0.top +
                                scroller.scrollTop
                            );

                        if (
                            Math.abs(
                                existing.lastY -
                                absY0
                            ) >
                            Math.max(
                                220,
                                scroller.clientHeight *
                                0.85
                            )
                        ) {
                            existing = null;
                        }
                    }
                }
            }

            if (!existing) {

                const rect =
                    el.getBoundingClientRect();

                const absY =
                    Math.round(
                        rect.top +
                        scroller.scrollTop
                    );

                const textHash =
                    hashText(text);

                existing =
                    messages.find(m => {

                        if (m.stableId) {
                            return false;
                        }

                        if (
                            m.role !== role
                        ) {
                            return false;
                        }

                        if (
                            m.textHash !==
                            textHash
                        ) {
                            return false;
                        }

                        return (
                            Math.abs(
                                m.lastY -
                                absY
                            ) <
                            Math.max(
                                220,
                                scroller.clientHeight *
                                0.85
                            )
                        );
                    });
            }

            if (existing) {

                existing.text = text;

                existing.lastScreen =
                    screenNo;

                existing.observations++;

                const rect =
                    el.getBoundingClientRect();

                existing.lastY =
                    Math.round(
                        rect.top +
                        scroller.scrollTop
                    );

                elementMessageMap.set(
                    el,
                    existing
                );

                duplicateObservationCount++;

                found.push(existing);

                continue;
            }

            const rect =
                el.getBoundingClientRect();

            const absY =
                Math.round(
                    rect.top +
                    scroller.scrollTop
                );

            const message = {

                index:
                    messages.length + 1,

                role,

                text,

                textHash:
                    hashText(text),

                stableId,

                firstScreen:
                    screenNo,

                lastScreen:
                    screenNo,

                firstY:
                    absY,

                lastY:
                    absY,

                observations:
                    1
            };

            messages.push(message);

            elementMessageMap.set(
                el,
                message
            );

            found.push(message);
        }

        return found;
    }

