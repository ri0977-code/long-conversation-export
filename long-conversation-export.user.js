    function collectNodes(
        site,
        scroller
    ) {

        // ---- Tier 1: 站点级 selector（已验证：ChatGPT / Doubao / Gemini）----
        // 11.1.4：站点配 forceTier2:true 时直接跳过 Tier 1，
        // 让 Tier 2 结构化收集兜底（Grok 用——Tier 1 testid 命中
        // 搜索 panel 本身，isInNoiseContext 对 Grok 的 React hash class 无效，
        // 必须放弃 Tier 1）。
        if (site.forceTier2 === true) {

            // 不跑 Tier 1，直接 fallthrough 到 Tier 2
        }
        else if (site.msgSelectors && site.msgSelectors.length) {

            // =====================================================
            // 11.2.0（2026-09-10 主人实测"grok 还是不行" → chrome-bridge 抓真实 DOM）
            //
            // 修 Bug①：**全部 selector 取并集**，
            // 不再"逐个试、首个命中就 return"。
            //
            // 根因（实测数据，不是推断）：
            //   Grok msgSelectors =
            //     [ [data-testid="user-message"],
            //       [data-testid="assistant-message"],
            //       [role=article] ]
            //   旧逻辑撞到第一个 user-message 命中 6 条就 return
            //   → 助手 6 条**永远抓不到**
            //   → __lcxDebug 实测 candidates:6 / final:6，且 6 条全是 user
            //   → 逐个命中数 6 / 6 / 12，并集 12 条 user/assistant 完美交替
            //
            // A/B 回归实测（本机 6 个真实站点，旧行为 vs 并集）：
            //   claude  6→6 ✅    deepseek 4→4 ✅   qwen    2→2 ✅
            //   chatgpt 4→4 ✅    doubao   4→4 ✅   grok    6→12 🔧修复
            //   —— 除 Grok 外集合**完全等价**，零回归。
            //
            // Gemini 同理受益（首个 user-query 以前会吃掉 model-response）。
            // =====================================================
            // 合并成**一条** querySelectorAll：
            //   · 浏览器原生按**文档序**返回（= 对话真实顺序）
            //   · 同一元素被多个 selector 命中时自动去重，只出一次
            //
            // 反面教材（chrome-bridge 在主人 Grok 页实测）：
            // 逐个 selector 依次 push 得到的是「按 selector 分组」的顺序，
            // 6 条 user 会全部排在 6 条 assistant 前面，**对话顺序被打乱**。
            //   逐个 push : user user user user user user assi assi assi assi assi assi
            //   合并查询 : user assi user assi user assi user assi user assi user assi
            let union = [];

            try {

                union = [
                    ...document.querySelectorAll(
                        site.msgSelectors.join(',')
                    )
                ];

            } catch (_) {

                // 有 selector 语法非法导致整条查询失败时，
                // 退回逐个查询 + 手动按文档序排序
                for (const sel of site.msgSelectors) {

                    let nodes = [];

                    try {

                        nodes = [
                            ...document.querySelectorAll(
                                sel
                            )
                        ];

                    } catch (__) {

                        continue;
                    }

                    for (const el of nodes) {

                        if (!union.includes(el)) {

                            union.push(el);
                        }
                    }
                }

                union.sort(
                    (a, b) =>
                        (
                            a.compareDocumentPosition(b) &
                            Node.DOCUMENT_POSITION_FOLLOWING
                        )
                            ? -1
                            : 1
                );
            }

            const visible =
                union.filter(
                    el =>
                        isVisibleMessage(
                            el,
                            scroller,
                            visibleOpts()
                        )
                );

            if (visible.length) {

                // 噪声过滤：把搜索面板 / 工具结果整节点丢掉
                //（grok 的搜索 panel 等）。
                const filtered =
                    stripNested(visible).filter(
                        el => !isInNoiseContext(el)
                    );

                if (filtered.length) {

                    return filtered;
                }
            }
        }

        // ---- Tier 2: 结构化收集（真通用，11.1.3 新增）----
        // 找消息容器 → 拿直接子节点 → 噪声过滤。
        // 不依赖任何 selector，grok 这种 selector 抓不准的站点
        // 也能用。
        const structured = structuredCollect(scroller);

        if (structured.length) {

            return structured;
        }

        // ---- Tier 3: 老 fallback（按"兄弟节点最多"猜）----
        return genericTurns(scroller).filter(
            el => !isInNoiseContext(el)
        );
    }

    function getMessageElements(
        scroller
    ) {

        let nodes =
            collectNodes(
                SITE,
                scroller
            );

        if (nodes.length) {
            return nodes;
        }

        nodes = [
            ...document.querySelectorAll(
                'article[data-testid*="conversation-turn"]'
            )
        ].filter(
            el =>
                isVisibleMessage(
                    el,
                    scroller,
                    visibleOpts()
                )
        );

        if (nodes.length) {
            return nodes;
        }

        nodes = [
            ...document.querySelectorAll(
                'article'
            )
        ].filter(
            el =>
                isVisibleMessage(
                    el,
                    scroller,
                    visibleOpts()
                )
        );

        return nodes;
    }

