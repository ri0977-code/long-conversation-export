    function roleFromText(s) {

        const t =
            String(s || '').toLowerCase();

        if (!t) return null;

        if (
            /(^|[^a-z])(user|human|question)([^a-z]|$)/.test(t) ||
            t.includes('用户') ||
            t.includes('提问') ||
            t.includes('我:') ||
            t.includes('我：')
        ) {
            return 'user';
        }

        if (
            /(assistant|chatgpt|gpt|claude|gemini|qwen|glm|deepseek|kimi|doubao|bot|model|agent)/.test(t) ||
            t.includes('助手') ||
            t.includes('回答') ||
            t.includes('ai')
        ) {
            return 'assistant';
        }

        return null;
    }

    function detectRole(el) {

        const attrRole =
            SITE.roleAttr &&
            el.getAttribute(
                SITE.roleAttr
            );

        if (attrRole) {

            const r =
                (
                    SITE.roleMap &&
                    SITE.roleMap[
                        String(
                            attrRole
                        ).toLowerCase()
                    ]
                ) ||
                String(
                    attrRole
                ).toLowerCase();

            if (
                r === 'user' ||
                r === 'human'
            ) {
                return 'user';
            }

            if (
                r === 'assistant' ||
                r === 'ai' ||
                r === 'model'
            ) {
                return 'assistant';
            }

            if (r === 'system') {
                return 'system';
            }
        }

        // 站点自定义角色规则（可选）：比通用启发式可靠得多，
        // 在通用探测之前生效。
        // 11.1.1：支持 `re`（正则匹配 className + roleAttr 值）。
        // 11.1.2：再加 `tag`（匹配 el.tagName.toLowerCase()）——
        //   Gemini 的 <user-query> / <model-response> 自定义元素就是
        //   靠 tag 判角色的，class 里反而没线索。
        //   `role: null` 表示「跳过这条规则，继续往下判」，
        //   让通用启发式兜底（不直接判失败、也不写死成某角色）。
        if (
            SITE.roleRules &&
            SITE.roleRules.length
        ) {

            const elTag = (
                el.tagName &&
                el.tagName.toLowerCase &&
                el.tagName.toLowerCase()
            ) || '';

            const hay = [
                (
                    el.className &&
                    String(el.className)
                ) || '',
                (
                    SITE.roleAttr &&
                    el.getAttribute(
                        SITE.roleAttr
                    )
                ) || ''
            ].join(' ');

            for (
                const rule of SITE.roleRules
            ) {

                if (!rule) continue;

                // tag 字段匹配
                if (
                    rule.tag &&
                    elTag === rule.tag.toLowerCase()
                ) {

                    if (rule.role === null) continue;
                    return rule.role;
                }

                // re 字段匹配
                if (
                    rule.re &&
                    rule.re.test(hay)
                ) {

                    if (rule.role === null) continue;
                    return rule.role;
                }
            }
        }

        const attrs = [
            'data-message-author-role',
            'data-role',
            'data-author',
            'data-testid',
            'aria-label'
        ];

        for (const a of attrs) {

            const r =
                roleFromText(
                    el.getAttribute(a)
                );

            if (r) return r;
        }

        const rc =
            roleFromText(
                el.className &&
                String(el.className)
            );

        if (rc) return rc;

        const userMark =
            el.querySelector(
                '[data-message-author-role="user"]'
            );

        if (userMark) {
            return 'user';
        }

        const assistantMark =
            el.querySelector(
                '[data-message-author-role="assistant"]'
            );

        if (assistantMark) {
            return 'assistant';
        }

        return 'unknown';
    }


    function isVisibleButton(el) {

        if (
            !el ||
            !el.isConnected
        ) {
            return false;
        }

        const s =
            getComputedStyle(el);

        if (
            s.display === 'none' ||
            s.visibility === 'hidden'
        ) {
            return false;
        }

        if (
            el.getClientRects().length === 0
        ) {
            return false;
        }

        const r =
            el.getBoundingClientRect();

        return (
            r.width > 10 &&
            r.height > 10
        );
    }

    function isExpandableButton(el) {

        // 性能优先：先做「便宜的文本判断」，只有命中候选才做
        // 昂贵的可见性检查。
        // isVisibleButton 内部有 getComputedStyle / getClientRects /
        // getBoundingClientRect，在大 DOM 上每次都会强制同步重排。
        // grok 这类页面有近 300 个按钮，而扫描每屏都要跑 3 轮
        // 全量遍历（≈870 次重排 ≈ 45 秒/屏），整条对话要扫半小时。
        // 另外这里用 textContent 而非 innerText —— innerText 同样
        // 会触发重排，而判断按钮文案用 textContent 已经足够。

        const text =
            normalizeText(
                el.textContent ||
                el.getAttribute(
                    'aria-label'
                ) ||
                ''
            );

        if (!text) return false;

        const exact = [
            '显示更多',
            '查看更多',
            '展开',
                 '展开全部',
            'show more',
            'view more',
            'expand',
            'read more',
            'show all',
            'view all',
            'expand all',
            '继续阅读',
            '展开更多',
                 'see more'
            // 注意：不要加裸 'more' —— 它会误命中各站点的
            // “more actions / 更多操作”菜单按钮（如 grok 每条消息的
            // ⋮菜单），点了只会弹菜单而非展开内容。
        ];

        const lower =
            text.toLowerCase();

        let matched = false;

        if (
            exact.some(
                x =>
                    lower ===
                    x.toLowerCase()
            )
        ) {
            matched = true;
        }

        const aria =
            String(
                el.getAttribute(
                    'aria-label'
                ) || ''
            ).toLowerCase();

        if (
            !matched &&
            aria &&
            (
                aria.includes(
                    'show more'
                ) ||
                aria.includes(
                    'view more'
                ) ||
                aria.includes(
                    'expand'
                ) ||
                aria.includes(
                    'read more'
                )
            )
        ) {
            matched = true;
        }

        // 只有走到这里（文本/aria 命中）才付出一次重排的代价
        if (!matched) return false;

        return isVisibleButton(el);
    }

    async function expandVisibleContent() {

        let clicked = 0;

        for (
            let round = 0;
            round < 3;
            round++
        ) {

            const buttons = [
                ...document.querySelectorAll(
                    'button'
                ),
                ...document.querySelectorAll(
                    '[role="button"]'
                )
            ];

            let changed = false;

            if (abortRequested) break;

            for (const btn of buttons) {

                if (abortRequested) break;

                if (
                    !isExpandableButton(btn)
                ) {
                    continue;
                }

                try {

                    btn.click();

                    clicked++;

                    changed = true;

                    await sleep(250);

                } catch (_) {}
            }

            if (!changed) {
                break;
            }

            await sleep(
                DOM_SETTLE_WAIT
            );
        }

        return clicked;
    }

