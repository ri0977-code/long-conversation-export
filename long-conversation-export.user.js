    // =========================================================
    // 通用滚动容器探测
    //
    // 不依赖任何 ChatGPT 特征，任何网页 / 长对话 / agent 界面都能用。
    // 思路：取「视口中心落在其中」且「可滚动距离最大」的那个容器；
    // 找不到就用 document.scrollingElement（整页滚动的站点）。
    // =========================================================

    function findGenericScroller() {

        const cx =
            window.innerWidth / 2;

        const cy =
            window.innerHeight / 2;

        let best = null;

        let bestRange = 0;

        for (
            const el of
            document.querySelectorAll('*')
        ) {

            // 性能：先用便宜的 scrollHeight/clientHeight 过滤掉
            // 绝大多数元素，只有候选才付出 getComputedStyle 的代价。
            // （原写法对每个元素都算样式，grok 这种大 DOM 上要 20~30 秒）

            const range =
                el.scrollHeight -
                el.clientHeight;

            if (range <= 50) continue;

            const s =
                getComputedStyle(el);

            if (
                !/auto|scroll|overlay/
                    .test(s.overflowY)
            ) {
                continue;
            }

            const r =
                el.getBoundingClientRect();

            if (
                r.width < 200 ||
                r.height < 200
            ) {
                continue;
            }

            if (
                cx < r.left ||
                cx > r.right ||
                cy < r.top ||
                cy > r.bottom
            ) {
                continue;
            }

            if (range > bestRange) {

                bestRange = range;

                best = el;
            }
        }

        if (best) return best;

        const de =
            document.scrollingElement;

        return (
            de &&
            de.scrollHeight -
            de.clientHeight > 50
        )
            ? de
            : (de || null);
    }

    // =========================================================
    // 寻找真正的 ChatGPT 对话滚动容器
    // 采用已经验证过的右侧滚动条机制
    // =========================================================

    function findRightScrollbarScroller() {

        const list = [];

        const all = document.querySelectorAll('*');

        for (const el of all) {

            const style = getComputedStyle(el);

            if (
                style.overflowY !== 'auto' &&
                style.overflowY !== 'scroll' &&
                style.overflowY !== 'overlay'
            ) {
                continue;
            }

            const rect =
                el.getBoundingClientRect();

            const range =
                el.scrollHeight - el.clientHeight;

            if (range <= 50) continue;

            if (rect.width < 300) continue;

            if (
                rect.height <
                window.innerHeight * 0.7
            ) {
                continue;
            }

            const rightDistance =
                Math.abs(
                    window.innerWidth - rect.right
                );

            if (rightDistance > 30) continue;

            if (
                rect.bottom <
                window.innerHeight * 0.5
            ) {
                continue;
            }

            let score = 0;

            score += Math.max(
                0,
                100 - rightDistance * 5
            );

            const heightRatio =
                rect.height / window.innerHeight;

            score += Math.min(
                100,
                heightRatio * 100
            );

            score += Math.max(
                0,
                50 - Math.abs(rect.top) * 2
            );

            score += Math.min(
                50,
                range / 1000
            );

            list.push({
                el,
                rect,
                range,
                score
            });
        }

        list.sort(
            (a, b) => b.score - a.score
        );

        return list.length
            ? list[0].el
            : null;
    }

    // =========================================================
    // 到真正顶部
    // =========================================================

    async function goToRealTop(input) {

        let scroller =
            input || findGenericScroller();

        if (!scroller) return false;

        for (let i = 1; i <= 10; i++) {

            if (abortRequested) break;

            scroller.scrollTop = 0;

            await sleep(WAIT);

            if (scroller.scrollTop <= 1) {

                let stable = 0;

                for (
                    let j = 0;
                    j < TOP_CONFIRM_TIMES;
                    j++
                ) {

                    if (abortRequested) break;

                    scroller.scrollTop = 0;

                    await sleep(500);

                    if (scroller.scrollTop <= 1) {
                        stable++;
                    } else {
                        stable = 0;
                    }
                }

                if (
                    stable >=
                    TOP_CONFIRM_TIMES
                ) {
                    return true;
                }
            }
        }

        return scroller.scrollTop <= 2;
    }

