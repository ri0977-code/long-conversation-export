    function getStableId(el) {

        const attrs = [
            'data-message-id',
            'data-id',
            'data-testid'
        ];

        for (const attr of attrs) {

            const v =
                el.getAttribute(attr);

            if (!v) continue;

            if (
                attr === 'data-testid'
            ) {

                if (
                    !/conversation-turn|message/i
                        .test(v)
                ) {
                    continue;
                }
            }

            return v;
        }

        return null;
    }

