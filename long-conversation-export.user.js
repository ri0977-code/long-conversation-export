    async function confirmBottom(
        scroller
    ) {

        const max =
            Math.max(
                0,
                scroller.scrollHeight -
                scroller.clientHeight
            );

        scroller.scrollTop = max;

        await sleep(WAIT);

        const after =
            scroller.scrollTop;

        if (
            Math.abs(
                after - max
            ) <= 3
        ) {

            scroller.scrollTop = max;

            await sleep(600);

            return (
                Math.abs(
                    scroller.scrollTop -
                    (
                        scroller.scrollHeight -
                        scroller.clientHeight
                    )
                ) <= 3
            );
        }

        return false;
    }

