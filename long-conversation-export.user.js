    function downloadText(
        content,
        filename,
        mime
    ) {

        const blob =
            new Blob(
                [content],
                {
                    type:
                        mime +
                        ';charset=utf-8'
                }
            );

        const url =
            URL.createObjectURL(blob);

        const a =
            document.createElement('a');

        a.href = url;

        a.download = filename;

        document.body.appendChild(a);

        a.click();

        a.remove();

        setTimeout(
            () => {
                URL.revokeObjectURL(url);
            },
            5000
        );
    }

    // =========================================================
    // 10.7.0：漏抓补扫
    //
    // 主扫描结束后，用每条消息记录的绝对 Y 位置算覆盖范围，
    // 找出「跨度超过一屏」的空洞，单独跳回去补采一次。
    // 只补洞，不整篇重扫，代价很小。
    // =========================================================

    async function repairGaps(
        scroller,
        screenNo,
        minY
    ) {

        const vh =
            scroller.clientHeight ||
            window.innerHeight;

        const spans = messages
            .filter(
                m =>
                    typeof m.firstY ===
                    'number'
            )
            .map(m => [
                Math.min(
                    m.firstY,
                    m.lastY
                ),
                Math.max(
                    m.firstY,
                    m.lastY
                )
            ])
            .sort(
                (a, b) => a[0] - b[0]
            );

        if (spans.length < 2) {
            return { gaps: 0, fixed: 0 };
        }

        const gaps = [];

        let reach = spans[0][1];

        for (
            let i = 1;
            i < spans.length;
            i++
        ) {

            if (
                spans[i][0] - reach >
                vh * 0.9
            ) {

                gaps.push([
                    reach,
                    spans[i][0]
                ]);
            }

            reach =
                Math.max(
                    reach,
                    spans[i][1]
                );
        }

        const before =
            messages.length;

        // 从指定位置开始时，起点以上的区域不属于本次任务，
        // 不要回头去补（否则又把上面的新闻简报抓进来了）
        const floor =
            typeof minY === 'number'
                ? Math.max(0, minY)
                : 0;

        for (
            const g of gaps.slice(0, 30)
        ) {

            if (abortRequested) break;

            if (g[1] <= floor) continue;

            const start =
                Math.max(
                    floor,
                    g[0] -
                    Math.round(vh * 0.3)
                );

            const end = g[1];

            const stepY =
                Math.max(
                    200,
                    Math.round(vh * 0.5)
                );

            for (
                let y = start;
                y <= end;
                y += stepY
            ) {

                if (abortRequested) break;

                scroller.scrollTop = y;

                await waitRendered();

                collectMessages(
                    scroller,
                    screenNo
                );
            }
        }

        finalizeMessages();

        return {
            gaps: gaps.length,
            fixed:
                messages.length -
                before
        };
    }

    // =========================================================
    // 11.0.0：起点锚点
    //
    // 「从当前位置开始扫描」时，先记住当前视口顶部往下第一条消息，
    // 展开折叠内容后页面高度会变，用它把起点重新对回来，
    // 否则起点会被顶下去几十上百像素，最上面那条可能漏掉。
    // =========================================================

    const ANCHOR_KEY_LEN = 160;

    function textOf(el) {

        return normalizeText(
            el.innerText ||
            el.textContent ||
            ''
        );
    }

    function makeAnchorFrom(el, scroller) {

        const t = textOf(el);

        if (!t) return null;

        const sr =
            scroller.getBoundingClientRect();

        const r =
            el.getBoundingClientRect();

        return {

            key:
                t.slice(
                    0,
                    ANCHOR_KEY_LEN
                ),

            offset: Math.round(
                r.top - sr.top
            ),

            absY: Math.round(
                r.top +
                scroller.scrollTop
            )
        };
    }

    /**
     * 起点锚点选取（11.0.2 重写）
     *
     * 默认**以屏幕为准**：取当前视口顶部往下第一条消息当起点。
     * 主人是用滚轮滚屏的，鼠标光标常常随便停在屏幕上某个位置，
     * 拿光标位置当起点必然不准 —— 所以点击产生的光标一律忽略。
     *
     * 只有一种例外：主人**真的拖选了一段文字**（selection 非折叠），
     * 这说明他明确在指某条消息，才用那条消息当锚点，并把它顶到视口顶部。
     */
    function pickStartAnchor(scroller) {

        try {

            const sel =
                window.getSelection &&
                window.getSelection();

            // 必须是真的选中了文字：点击造成的光标（isCollapsed）不算
            if (
                sel &&
                !sel.isCollapsed &&
                sel.rangeCount > 0 &&
                sel.anchorNode
            ) {

                let node =
                    sel.anchorNode;

                if (
                    node.nodeType === 3
                ) {
                    node =
                        node.parentNode;
                }

                const nodes =
                    getMessageElements(
                        scroller
                    );

                const set =
                    new Set(nodes);

                let p = node;

                while (
                    p &&
                    p !== document.body
                ) {

                    if (set.has(p)) {

                        const a =
                            makeAnchorFrom(
                                p,
                                scroller
                            );

                        if (a) {

                            a.fromSelection =
                                true;

                            // 把这条消息顶到视口顶部
                            const sr =
                                scroller
                                    .getBoundingClientRect();

                            const r =
                                p.getBoundingClientRect();

                            scroller.scrollTop =
                                Math.max(
                                    0,
                                    Math.round(
                                        scroller.scrollTop +
                                        r.top -
                                        sr.top -
                                        8
                                    )
                                );

                            a.offset = 8;

                            return a;
                        }
                    }

                    p =
                        p.parentElement;
                }
            }

        } catch (_) {}

        // 没有选区：视口顶部往下第一条消息
        try {

            const sr =
                scroller.getBoundingClientRect();

            const nodes =
                getMessageElements(
                    scroller
                );

            for (const el of nodes) {

                const r =
                    el.getBoundingClientRect();

                if (
                    r.bottom <=
                    sr.top + 4
                ) {
                    continue;
                }

                const a =
                    makeAnchorFrom(
                        el,
                        scroller
                    );

                if (a) return a;
            }

        } catch (_) {}

        return null;
    }

    /**
     * 起点重对齐（11.0.1）
     *
     * 展开折叠内容后页面会变高，绝对坐标整体下移，
     * 原来那个 scrollTop 对应的内容就"往回跑"了。
     * 用锚点文本（160 字符，比 60 字符稳得多）把起点重新对回来。
     *
     * 注意：只在锚点还「在 DOM 里」时才动，找不到就原样返回 false，
     * 宁可不动也别乱跳 —— 11.0.0 用 60 字符前缀乱匹配就是往上跳几屏的元凶。
     */
    function realignStart(
        scroller,
        anchor
    ) {

        if (!anchor || !anchor.key) {
            return false;
        }

        const sr =
            scroller.getBoundingClientRect();

        const nodes =
            getMessageElements(
                scroller
            );

        let best = null;

        for (const el of nodes) {

            const t =
                textOf(el);

            if (!t) continue;

            // 必须是同一条消息：160 字符全等才算命中
            if (
                t.slice(
                    0,
                    ANCHOR_KEY_LEN
                ) !== anchor.key
            ) {
                continue;
            }

            const r =
                el.getBoundingClientRect();

            const delta =
                r.top -
                sr.top -
                anchor.offset;

            // 取偏差最小的那个候选，避免撞上文本相同的另一条
            if (
                !best ||
                Math.abs(delta) <
                Math.abs(best.delta)
            ) {

                best = {
                    delta,
                    r
                };
            }
        }

        if (!best) return false;

        if (
            Math.abs(best.delta) < 4
        ) {
            return false;
        }

        scroller.scrollTop =
            Math.max(
                0,
                Math.round(
                    scroller.scrollTop +
                    best.delta
                )
            );

        return true;
    }

    /**
     * 导出前裁剪：丢掉起点锚点之前的所有消息（11.0.1）
     *
     * 这是最后一道保险 —— 不管扫描过程中位置怎么漂，
     * 只要锚点那条消息被抓到了，就一定能把它前面的全切掉。
     */
    function trimAboveStart(anchor) {

        if (
            !anchor ||
            !anchor.key
        ) {
            return 0;
        }

        let idx = -1;

        for (
            let i = 0;
            i < messages.length;
            i++
        ) {

            if (
                !messages[i].text
            ) {
                continue;
            }

            if (
                messages[i]
                    .text
                    .slice(
                        0,
                        ANCHOR_KEY_LEN
                    ) === anchor.key
            ) {

                idx = i;

                break;
            }
        }

        if (idx <= 0) return 0;

        messages.splice(0, idx);

        return idx;
    }

