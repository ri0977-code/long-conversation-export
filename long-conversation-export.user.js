    function renderIds() {

        let nodes = [];

        for (
            const sel of SITE.msgSelectors
        ) {

            try {

                nodes = [
                    ...document.querySelectorAll(
                        sel
                    )
                ];

            } catch (_) {
                continue;
            }

            if (nodes.length) break;
        }

        if (!nodes.length) {

            nodes = [
                ...document.querySelectorAll(
                    '[data-message-author-role]'
                )
            ];
        }

        return nodes
            .map(
                e =>
                    (e.getAttribute(
                        'data-message-id'
                    ) || '') +
                    ':' +
                    (e.textContent || '')
                        .length
            )
            .join('|');
    }

    async function waitRendered(maxMs) {

        const limit =
            maxMs || 1500;

        const t0 = Date.now();

        let last = '';

        let stable = 0;

        while (
            Date.now() - t0 < limit
        ) {

            // 用户点了停止：别再干等虚拟列表渲染
            if (abortRequested) {
                return true;
            }

            const ids =
                renderIds();

            if (ids && ids === last) {

                stable++;

                if (stable >= 2) {
                    return true;
                }

            } else {

                stable = 0;
            }

            last = ids;

            await sleep(120);
        }

        return false;
    }

