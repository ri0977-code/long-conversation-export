    function hasHiddenAncestor(el) {

        let p = el;

        while (
            p &&
            p !== document.body
        ) {

            if (
                p.getAttribute &&
                p.getAttribute(
                    'aria-hidden'
                ) === 'true'
            ) {
                return true;
            }

            const s =
                getComputedStyle(p);

            if (
                s.display === 'none' ||
                s.visibility === 'hidden'
            ) {
                return true;
            }

            p = p.parentElement;
        }

        return false;
    }

    function isVisibleMessage(
        el,
        scroller,
        opts
    ) {

        if (
            !el ||
            !el.isConnected
        ) {
            return false;
        }

        if (
            hasHiddenAncestor(el)
        ) {
            return false;
        }

        const style =
            getComputedStyle(el);

        if (
            style.display === 'none' ||
            style.visibility === 'hidden' ||
            style.opacity === '0'
        ) {
            return false;
        }

        if (
            el.getClientRects().length === 0
        ) {
            return false;
        }

        const r =
            el.getBoundingClientRect();

        if (
            r.width < 30 ||
            r.height < 5
        ) {
            return false;
        }

        // =========================================================
        // 11.1.9（2026-09-10 主人实测"grok 还是不行" → chrome-bridge 抓真实 DOM）
        //
        // 全量 DOM 渲染站点（Grok）豁免「距视口过远」过滤。
        //
        // 实测依据（chrome-bridge 在主人 Grok 对话页抓的真实数据）：
        //   · 12 条消息（user/assistant 各 6）**全部常驻 DOM**
        //     → scroller scrollHeight = 11510 ≈ 12 条消息高度合计 10701
        //   · 每条 disp=block / vis=visible / opacity=1 / isConnected=true
        //     —— 全都"活着"，只是位置被滚到视口外
        //   · 通用 margin（max(45% 屏高, 300) = 406）把这些消息判为
        //     "离视口太远" 而滤掉 → 12 条只剩 1 条 → 扫描到底 0 条消息
        //     （面板显示"第 4 屏 · 18% · 已发现 0 条消息"）
        //   · 豁免距离过滤后实测 kept = 12/12（user/assistant 完美交替）
        //
        // 只放开"距离"，硬性可见性检查一律保留：
        //   isConnected / hasHiddenAncestor / display:none / visibility /
        //   opacity:0 / getClientRects 为空 / 尺寸 < 30×5
        // =========================================================
        if (
            opts &&
            opts.ignoreViewportDistance === true
        ) {
            return true;
        }

        const sr =
            scroller.getBoundingClientRect();

        const margin =
            Math.max(
                window.innerHeight * 0.45,
                300
            );

        if (
            r.bottom <
            sr.top - margin
        ) {
            return false;
        }

        if (
            r.top >
            sr.bottom + margin
        ) {
            return false;
        }

        return true;
    }

    // =========================================================
    // 消息节点识别
    // =========================================================

    // =========================================================
    // 11.2.0：全量 DOM 渲染站点（Grok）「距离过滤豁免」的统一入口。
    //
    // 铁律：凡是对「已收集到的消息」再做二次可见性过滤的地方，
    // 都必须传 visibleOpts()。否则会把 Tier 1 刚豁免掉的距离过滤
    // 又砍回来 —— 这正是 11.1.9 没修好的真凶：
    //   collectMessages 里那次 isVisibleMessage(el, scroller) 没传 opts，
    //   chrome-bridge 实测 12 条被二次过滤杀到只剩 1 条，
    //   面板报「本次抓到 0 条」（而 __lcxDebug 明明说 6 条）。
    // =========================================================
    function visibleOpts() {

        return {
            ignoreViewportDistance:
                !!(
                    SITE &&
                    SITE.fullDomRender === true
                )
        };
    }

    function stripNested(nodes) {

        const set = new Set(nodes);

        return nodes.filter(el => {

            let p = el.parentElement;

            while (
                p &&
                p !== document.body
            ) {

                if (set.has(p)) {
                    return false;
                }

                p = p.parentElement;
            }

            return true;
        });
    }

    /**
     * 通用兜底：把「同一个父容器下、文本较长的兄弟节点」
     * 当成一轮轮对话。大多数聊天站点都是这个结构。
     */
    function genericTurns(scroller) {

        const cands = [
            ...document.querySelectorAll(
                'div,li,article,section'
            )
        ].filter(
            el =>
                isVisibleMessage(
                    el,
                    scroller,
                    visibleOpts()
                ) &&
                (
                    el.innerText || ''
                ).trim().length > 30
        );

        const byParent = new Map();

        for (const el of cands) {

            const p =
                el.parentElement;

            if (!p) continue;

            const arr =
                byParent.get(p) || [];

            arr.push(el);

            byParent.set(p, arr);
        }

        let best = [];

        let bestScore = 0;

        for (
            const [p, arr] of byParent
        ) {

            if (arr.length < 2) {
                continue;
            }

            let depth = 0;

            let q = p;

            while (q) {
                depth++;
                q = q.parentElement;
            }

            const score =
                arr.length * 100 + depth;

            if (score > bestScore) {

                bestScore = score;

                best = arr;
            }
        }

        return best;
    }

    // =========================================================
    // 11.1.3：噪声容器识别（关键修复：grok 的"对话里的搜索"）
    //
    // 主人实测 grok 11.1.1/11.1.2 都把搜索结果当消息抓。
    // 根因：grok 的搜索结果是同级 div，用任何 selector 都会同时命中。
    // 修法：每个候选消息沿 DOM 向上 6 层查祖先的 class/id/aria-label/
    // data-* 是否含噪声词。命中 = 是搜索面板/工具结果/附件预览的子元素，
    // 直接跳过，不再当消息。
    // =========================================================

    // 噪声关键词。**子串匹配**（不分大小写），命中 class/id/aria-label/
    // data-* 任一即视为噪声容器。
    // 英文用常见命名：search / web-search / x-search / tool / function /
    // artifact / attachment / upload / citation-source / x-citation。
    // 中文用对话内可能出现的：搜索 / 工具 / 函数 / 附件 / 代码块。
    // 排除"code"是因为消息里内嵌的代码块 div 也会被命中，但那种是
    // 消息的一部分不是单独元素；真要排除代码块用 "code-block"/"codeblock"。
    const NOISE_PATTERNS = [
        'search',
        'web-search',
        'x-search',
        'tool',
        'function',
        'artifact',
        'attachment',
        'upload',
        'file-upload',
        'citation',
        'codeblock',
        'code-block',
        '搜索',
        '工具',
        '函数',
        '附件',
        '代码块'
    ];

    function matchesNoisePattern(str) {

        if (!str) return false;

        const s = String(str).toLowerCase();

        for (const p of NOISE_PATTERNS) {

            if (s.includes(p.toLowerCase())) {

                return true;
            }
        }

        return false;
    }

    /**
     * 检查 el 自身或祖先（最多 6 层）是否落在噪声容器里。
     * 返回噪声类名（"search"/"tool"/...），没命中返回 null。
     */
    function isInNoiseContext(el) {

        if (!el) return null;

        let cur = el;
        let depth = 0;

        while (cur && depth < 6) {

            // class / id
            if (
                matchesNoisePattern(cur.className) ||
                matchesNoisePattern(cur.id)
            ) {

                return cur.className || cur.id;
            }

            // aria-label / role
            const ariaLabel =
                cur.getAttribute &&
                cur.getAttribute('aria-label');

            const role =
                cur.getAttribute &&
                cur.getAttribute('role');

            if (
                matchesNoisePattern(ariaLabel) ||
                matchesNoisePattern(role)
            ) {

                return ariaLabel || role;
            }

            // data-testid / data-message-author-role / data-author / data-source
            const dataAttrs = [
                'data-testid',
                'data-message-author-role',
                'data-author',
                'data-source',
                'data-type'
            ];

            for (const a of dataAttrs) {

                const v =
                    cur.getAttribute &&
                    cur.getAttribute(a);

                if (matchesNoisePattern(v)) {

                    return v;
                }
            }

            cur = cur.parentElement;
            depth++;
        }

        return null;
    }

    /**
     * 11.1.3：找"消息容器"——scroller 内部、**最深、且直接子节点 ≥ 3** 的 div。
     * 现代 AI 站点的对话区都是这个结构：一个 wrapper 装着 N 条消息。
     * "最深"是因为有时大容器套小容器，要找最里层那个。
     */
    function findConversationContainer(scroller) {

        if (!scroller) return null;

        let best = null;
        let bestScore = 0;

        // 从 scroller 里所有 div 找
        const all = scroller.querySelectorAll('div');

        for (const d of all) {

            // 必须直接在 scroller 内或浅层（避免选到 tool-tip 这种浮动小窗）
            if (!scroller.contains(d)) continue;

            const kids = d.children;

            if (!kids || kids.length < 3) continue;

            // 直接子节点中至少有 2 个 div（消息通常也是 div）
            let divKids = 0;

            for (let i = 0; i < kids.length; i++) {

                if (kids[i].tagName === 'DIV') {
                    divKids++;
                }
            }

            if (divKids < 2) continue;

            // 自身不能是噪声容器
            if (isInNoiseContext(d)) continue;

            // 深度越深越好（最像"直接装着消息"的容器）
            let depth = 0;
            let q = d;
            while (q && q !== scroller) {
                depth++;
                q = q.parentElement;
            }

            // 评分：直接子节点数 × 10 + 深度。子节点多 + 深 = 胜出
            const score = kids.length * 10 + depth;

            if (score > bestScore) {

                bestScore = score;
                best = d;
            }
        }

        return best;
    }

    /**
     * 11.1.3：结构化收集——拿消息容器的直接子节点当消息。
     * 这是"真通用"的核心：不再依赖任何站点的具体 selector。
     */
    function structuredCollect(scroller) {

        const container =
            findConversationContainer(scroller);

        if (!container) return [];

        const out = [];

        for (let i = 0; i < container.children.length; i++) {

            const child = container.children[i];

            // 自身就是噪声 → 跳
            if (isInNoiseContext(child)) continue;

            // 文本太短（按钮/avatar/分隔线）→ 跳
            const text = (child.innerText || child.textContent || '').trim();

            if (text.length < 3) continue;

            out.push(child);
        }

        return out;
    }

