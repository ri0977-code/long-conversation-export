    function normalizeText(text) {

        return String(text || '')
            .replace(/\u200B/g, '')
            .replace(/\u00A0/g, ' ')
            .replace(/\r/g, '')
            .replace(/[ \t]+/g, ' ')
            .replace(/\n{3,}/g, '\n\n')
            .trim();
    }

    function hashText(text) {

        let h = 2166136261;

        for (let i = 0; i < text.length; i++) {

            h ^= text.charCodeAt(i);

            h = Math.imul(h, 16777619);
        }

        return (h >>> 0).toString(16);
    }

